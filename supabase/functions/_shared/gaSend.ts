export interface FejletAfsendelse { event_id: string; udfald: SporUdfald; fejl: string | null; forsoeg: number }

export function alarmTekst(fejlede: readonly FejletAfsendelse[], nu: Date): { emne: string; titel: string; afsnit: string[]; blokke: { overskrift: string; tekst: string }[]; tekst: string } {
  const n = fejlede.length;
  const hvad = n === 1 ? "1 GA-hændelse" : `${n} GA-hændelser`;
  const emne = `${hvad} kunne ikke sendes — Google Analytics har brug for et menneske`;
  const titel = `Google Analytics: ${hvad} kunne ikke sendes (${kbhDato(nu)})`;
  const ugyldig = fejlede.some((f) => f.udfald === "ugyldig");
  const afsnit = [
    `ga-send-cron kunne ikke sende ${hvad} til Google Analytics (${GA_MEASUREMENT_ID}). Ansøgningerne er urørte — kun målingen mangler.`,
    ugyldig
      ? "Mindst én blev afvist af valideringen («ugyldig») — den prøves ikke igen, før payloaden er rettet. Kør en tørkørsel med debug og læs validationMessages."
      : `Fejl og timeout prøves igen ved hver kørsel, så længe hændelsen er under ${GA_VINDUE_TIMER} timer gammel — vinduet er loftet, ikke et forsøgstal.`,
  ];
  const blokke = fejlede.slice(0, 5).map((f) => ({ overskrift: f.event_id, tekst: `${f.udfald} · forsøg ${f.forsoeg}${f.fejl ? ` — ${f.fejl}` : ""}` }));
  const tekst = [emne, ...afsnit, "", ...blokke.map((b) => `${b.overskrift}: ${b.tekst}`), "", "Sporet: ga_haendelser. Tørkørsel: SELECT public.kald_edge('ga-send-cron');"].join("\n");
  return { emne, titel, afsnit, blokke, tekst };
}
