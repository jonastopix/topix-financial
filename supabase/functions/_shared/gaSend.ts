/** Backdating-grænsen. */
export const GA_VINDUE_TIMER = 72;
/** Grænsen for at kunne joines med gtag.js-hændelser. Mellem de to sendes der stadig. */
export const GA_JOIN_TIMER = 48;
/** Googles eksempelværdi — ikke en måling. */
export const ENGAGEMENT_TIME_MSEC = 100;
/** Googles grænse for en parameterværdi på en standard-ejendom. */
export const VAERDI_MAKS = 100;

export const ARTER = ["started", "submitted"] as const;
export type Art = (typeof ARTER)[number];

/** Samme to navne som hjemmesidens GTM-tags (docs/tracking.md §1b). Begge ≤ 40 tegn og ikke reserverede. */
export const GA_EVENT_NAVN: Readonly<Record<Art, string>> = {
  started: "application_started",
  submitted: "application_submitted",
};

/** Sporets nøgle. Sendes IKKE til Google (MP har ingen dedup) — den er vores egen. */
export function eventId(ansoegningId: string, art: Art): string {
  return `${ansoegningId}:${art}`;
}

const somTid = (v: string | null | undefined): Date | null => {
  if (typeof v !== "string" || v.trim() === "") return null;
  const t = Date.parse(v);
  return Number.isFinite(t) ? new Date(t) : null;
};

/** Inden for Googles backdating-vindue: 0 ≤ nu − tid ≤ 72 timer. */
export function erIVindue(tid: Date, nu: Date): boolean {
  const alder = nu.getTime() - tid.getTime();
  return alder >= 0 && alder <= GA_VINDUE_TIMER * 3_600_000;
}

/** Kan hændelsen stadig joines med besøget? Under 48 t. Sendes uanset — men svaret siger det. */
export function kanJoines(tid: Date, nu: Date): boolean {
  return nu.getTime() - tid.getTime() <= GA_JOIN_TIMER * 3_600_000;
}

/** Rækken, cronen læser — og INTET andet (ingen navn, email, telefon, cvr, svar, user agent, fbclid). */
export interface AnsoegningTilGa {
  id: string;
  created_at: string;
  indsendt_at: string | null;
  ga_client_id: string | null;
  ga_session_id: string | null;
  kilde: string | null;
  utm_source: string | null;
  utm_medium: string | null;
  utm_campaign: string | null;
  utm_content: string | null;
  utm_term: string | null;
}

export const SPRUNGET_GRUNDE = ["ingen_ga_client_id", "ikke_indsendt", "ingen_tidspunkt", "for_gammel"] as const;
export type SprungetGrund = (typeof SPRUNGET_GRUNDE)[number];

export type Dom = { ok: true; tid: Date } | { ok: false; grund: SprungetGrund };

/** Dommen pr. (ansøgning, art): må den sendes, og med hvilket tidspunkt? */
export function doem(r: AnsoegningTilGa, art: Art, nu: Date): Dom {
  if (!r.ga_client_id || r.ga_client_id.trim() === "") return { ok: false, grund: "ingen_ga_client_id" };
  if (art === "submitted" && !r.indsendt_at) return { ok: false, grund: "ikke_indsendt" };
  const tid = somTid(art === "started" ? r.created_at : r.indsendt_at);
  if (tid === null) return { ok: false, grund: "ingen_tidspunkt" };
  if (!erIVindue(tid, nu)) return { ok: false, grund: "for_gammel" };
  return { ok: true, tid };
}

export interface GaPayload {
  client_id: string;
  timestamp_micros: number;
  events: [{ name: string; params: Record<string, string | number> }];
}

/** Parametrenes navne — ingen begynder med _, firebase_, ga_, google_ eller gtag. (Googles reserverede præfikser). */
export const PARAMETER_NAVNE = ["kilde", "utm_source", "utm_medium", "utm_campaign", "utm_content", "utm_term"] as const;

const vaerdi = (v: string | null | undefined): string | null => {
  if (typeof v !== "string") return null;
  const t = v.trim().slice(0, VAERDI_MAKS);
  return t === "" ? null : t;
};

/**
 * Payloaden — præcis de tilladte felter. session_id UDELADES, når vi ikke har et: Google
 * siger, at et NYT session_id skaber en ny session, og en opfundet session ville skille
 * ansøgerens besøg i to. Kilden og utm-mærkerne sendes som almindelige event-parametre;
 * de ses først i rapporter, når de er oprettet som brugerdefinerede dimensioner, og de
 * ÆNDRER IKKE GA4's egen trafikkilde-tilskrivning (det bærer dokumentationen ikke — se
 * README). Ingen campaign_details-hændelse: den ville tilskrive en kampagne, og det er
 * ikke vores at gøre server-side.
 */
export function bygPayload(r: AnsoegningTilGa, art: Art, tid: Date): GaPayload {
  const params: Record<string, string | number> = { engagement_time_msec: ENGAGEMENT_TIME_MSEC };
  const session = vaerdi(r.ga_session_id);
  if (session !== null) params.session_id = session;
  for (const navn of PARAMETER_NAVNE) {
    const v = vaerdi(r[navn]);
    if (v !== null) params[navn] = v;
  }
  return {
    client_id: (r.ga_client_id ?? "").trim(),
    timestamp_micros: tid.getTime() * 1000,
    events: [{ name: GA_EVENT_NAVN[art], params }],
  };
}

/**
 * Nøgler, der ALDRIG må stå i det, vi sender til Google (deres politik + vores egne felter).
 * BEMÆRK, at «name» IKKE står her: det er Googles eget påkrævede felt på en hændelse
 * (`events[].name`). Den fejl fangede prøven, første gang listen blev skrevet — derfor
 * står bemærkningen her, så ingen føjer det tilbage i den tro, at det betyder «navn».
 */
export const FORBUDTE_NOEGLER = [
  "email", "em", "ph", "navn", "telefon", "phone", "cvr", "svar", "udfordring", "hjemmeside",
  "virksomhedsnavn", "ip", "ip_hash", "client_ip_address", "user_agent", "client_user_agent",
  "fbclid", "fbc", "fbp", "user_id", "address", "user_data", "landing", "referrer",
] as const;

/** Stierne til enhver forbudt nøgle i objektet — tom = rent. */
export function findForbudteNoegler(obj: unknown, sti = ""): string[] {
  if (obj === null || typeof obj !== "object") return [];
  const ud: string[] = [];
  if (Array.isArray(obj)) { obj.forEach((v, i) => ud.push(...findForbudteNoegler(v, `${sti}[${i}]`))); return ud; }
  for (const [k, v] of Object.entries(obj as Record<string, unknown>)) {
    const her = sti ? `${sti}.${k}` : k;
    if ((FORBUDTE_NOEGLER as readonly string[]).includes(k)) ud.push(her);
    ud.push(...findForbudteNoegler(v, her));
  }
  return ud;
}

/** Låsen: kun boolean true eller strengen "true" åbner. Alt andet (null, "ja", 1) er lukket. */
export function laasErAktiv(configValue: unknown): boolean {
  return configValue === true || configValue === "true";
}

/**
 * Sender kørslen noget? Kræver dry_run: false OG (låsen ELLER debug).
 * debug rammer valideringsserveren, som IKKE lander i rapporter — derfor tilladt uden lås.
 */
export function senderRigtigt(a: { dryRun: boolean; laasAktiv: boolean; debug: boolean }): boolean {
  if (a.dryRun) return false;
  return a.laasAktiv || a.debug;
}

// ── Sporet (ga_haendelser) ───────────────────────────────────────────────────

export const SPOR_UDFALD = ["sendt", "fejl", "timeout", "ugyldig", "ingen_noegle"] as const;
export type SporUdfald = (typeof SPOR_UDFALD)[number];

export interface SporRaekke {
  event_id: string;
  udfald: SporUdfald;
  forsoeg: number;
}

/**
 * SKAL KALDET I SPORET? (rettelse 21/9 aften — fejlen i #1073.)
 *
 * FEJLEN: en debug-kørsel (`dry_run: false` + `debug: true`) rammer Googles valideringsserver,
 * som IKKE lander i rapporter — men den upsertede alligevel sporet med udfald «sendt» og
 * `sendt_at` sat. `maaForsoeges` så kun på udfaldet, så den RIGTIGE afsendelse bagefter sprang
 * hændelsen over som «allerede_sendt». README's egen bevisrækkefølge (bevis 2 debug → bevis 3
 * rigtig) ville derfor have fejlet: valideringen ville have spist beviset.
 *
 * RETTELSEN — og hvorfor den er skruet sådan sammen: i stedet for at lære `maaForsoeges` at
 * læse `debug` (og dermed have en regel, nogen kan glemme ét sted), fjernes MULIGHEDEN for
 * at forveksle: **en debug-kørsel skriver kun i sporet, når valideringen siger NEJ.** Så kan
 * der aldrig opstå en række med «sendt» og `debug = true`, og `maaForsoeges` kan blive ved
 * med at dømme på udfaldet alene.
 *
 * Tre grunde til at det er den robuste løsning frem for et ekstra `debug`-argument:
 *   1. Sandheden står i rækken selv. Enhver læser — et menneske, en SQL, en fremtidig
 *      funktion — kan stole på, at «sendt» betyder «hændelsen er i GA».
 *      `ga_haendelser_sendt_hel` (CHECK: (udfald = 'sendt') = (sendt_at is not null)) holder
 *      dermed op med at kunne lyve.
 *   2. Den fejler sikkert. Glemmer nogen reglen, findes der ingen række — og ingen række
 *      betyder «prøv igen», ikke «spring over».
 *   3. Den kræver ingen ny tilstand og ingen skemaændring på en tabel, der allerede er kørt
 *      i prod (21/9 kl. 17:48).
 *
 * Valideringens NEJ skrives derimod ALTID: «ugyldig» er den ene ting, en debug-kørsel må
 * huske, fordi payloaden så er forkert og ikke skal sendes, før den er rettet. Fejl, timeout
 * og manglende nøgle i en debug-kørsel skrives ikke: de siger intet om hændelsen, kun om
 * valideringsserveren, og de står i svaret.
 */
export function skalSkriveSpor(udfald: SporUdfald, debug: boolean): boolean {
  return debug ? udfald === "ugyldig" : true;
}

/**
 * Idempotensen — og VINDUET ER LOFTET. Der er intet forsøgsloft: så længe hændelsen er
 * inden for 72 timer, prøver vi igen (Measurement Protocol svarer aldrig med en fejlkode,
 * så et «fejl» er netværk eller 5xx — forbigående af natur). «sendt» sendes aldrig igen,
 * fordi Google ikke dedup'er; «ugyldig» (valideringen sagde nej) sendes ikke igen, før
 * payloaden er rettet.
 *
 * DEN DØMMER PÅ UDFALDET ALENE — med vilje. Den behøver ikke kende `debug`, fordi
 * `skalSkriveSpor` sørger for, at en debug-kørsel aldrig efterlader en «sendt»-række
 * (rettelse 21/9 aften). Skulle nogen en dag skrive en alligevel, ville denne dom sige
 * «allerede_sendt» om noget, der aldrig nåede Google — derfor låser gaSend.guard dom 6,
 * at upsert'en går gennem skalSkriveSpor.
 */
export function maaForsoeges(spor: SporRaekke | null): { ok: true } | { ok: false; grund: "allerede_sendt" | "ugyldig" } {
  if (!spor) return { ok: true };
  if (spor.udfald === "sendt") return { ok: false, grund: "allerede_sendt" };
  if (spor.udfald === "ugyldig") return { ok: false, grund: "ugyldig" };
  return { ok: true };
}

export interface Valideringsbesked { fieldPath?: string; description?: string; validationCode?: string }

/**
 * Svaret. I en DEBUG-kørsel betyder «sendt» kun, at valideringen ikke havde indvendinger —
 * hændelsen er IKKE i GA («Events sent to the validation server don't show up in reports»).
 * Kørslen tæller den derfor som `valideret`, og `skalSkriveSpor` holder den ude af sporet.
 *
 * Produktions-endpointet siger intet (Googles egne ord ovenfor): 2xx = «sendt»,
 * og en forkert api_secret ville se nøjagtig sådan ud. Valideringsserveren svarer med
 * validationMessages: tom liste = gyldig, ellers «ugyldig» med beskederne.
 */
export function doemGaSvar(status: number, tekst: string, debug: boolean): { udfald: SporUdfald; validering: Valideringsbesked[] | null; fejl: string | null } {
  if (status === 401 || status === 403) return { udfald: "ingen_noegle", validering: null, fejl: `HTTP ${status}` };
  if (status < 200 || status >= 300) return { udfald: status >= 500 ? "fejl" : "ugyldig", validering: null, fejl: `HTTP ${status}: ${tekst.slice(0, 200)}` };
  if (!debug) return { udfald: "sendt", validering: null, fejl: null };
  let krop: { validationMessages?: Valideringsbesked[] } | null = null;
  try { krop = JSON.parse(tekst) as { validationMessages?: Valideringsbesked[] }; } catch { krop = null; }
  if (krop === null) return { udfald: "ugyldig", validering: null, fejl: `valideringssvaret kunne ikke læses: ${tekst.slice(0, 200)}` };
  const beskeder = krop.validationMessages ?? [];
  if (beskeder.length === 0) return { udfald: "sendt", validering: [], fejl: null };
  return { udfald: "ugyldig", validering: beskeder, fejl: beskeder.map((b) => `${b.validationCode ?? "?"} ${b.fieldPath ?? ""}: ${b.description ?? ""}`.trim()).join(" · ").slice(0, 300) };
}

